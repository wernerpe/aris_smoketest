# THE CROSS-CHECK: FK walked over the URDF's own XML vs frames.py
# ==========================================================================
def urdf_link_poses(root, q_by_joint):
    """Walk the URDF tree from `world` -> {link: (4,4) world pose}.

    Deliberately independent of everything else in the repo: this reads the
    file, nothing else, so agreement with `frames.fk` is evidence about the
    file rather than about a shared helper.
    """
    js = []
    for j in root.findall("joint"):
        ax = j.find("axis")
        js.append(dict(name=j.get("name"), type=j.get("type"),
                       parent=j.find("parent").get("link"),
                       child=j.find("child").get("link"), T=_origin_of(j),
                       axis=np.array([float(v) for v in ax.get("xyz").split()]
                                     if ax is not None else [0, 0, 1.0])))
    out = {"world": np.eye(4)}
    pending = list(js)
    while pending:
        moved = False
        for j in list(pending):
            if j["parent"] not in out:
                continue
            T = out[j["parent"]] @ j["T"]
            if j["type"] == "revolute":
                Tq = np.eye(4)
                Tq[:3, :3] = frames.rot_axis(j["axis"],
                                             q_by_joint.get(j["name"], 0.0))
                T = T @ Tq
            elif j["type"] != "fixed":
                raise AssertionError(f"unexpected joint type {j['type']}")
            out[j["child"]] = T
            pending.remove(j)
            moved = True
        assert moved, f"URDF chain is not connected to world: {pending[:3]}"
    return out


def _sample_qs(n=16, seed=20260825):
    rng = np.random.default_rng(seed)
    qs = [np.asarray(next(iter(FLEET_PROPOSED.values())).q_seed, float)]
    qs += list(rng.uniform(FR3_MIN + 0.10, FR3_MAX - 0.10, size=(n, 7)))
    return qs


def test_pen_tip_fk_matches_frames(root):
    """The URDF's pen_tip == frames FK + the fleet base transform.

    `pen_lat` is passed EXPLICITLY (the module global stays inline); this is
    the lateral holder, which is what the proposed rig carries.
    """
    off = tool_offset(PEN_EXT_HOLDER, PEN_LAT_HOLDER)
    worst = 0.0
    for q in _sample_qs():
        qmap = {f"arm{a}_panda_joint{i + 1}": q[i]
                for a in FLEET_PROPOSED for i in range(7)}
        poses = urdf_link_poses(root, qmap)
        T_b, _ = fk(q)                       # hand TCP in link0, frames DH
        for aid, spec in FLEET_PROPOSED.items():
            Twb = spec.T_world_base(H_INV)
            p_want = Twb[:3, :3] @ (T_b[:3, 3] + T_b[:3, :3] @ off) + Twb[:3, 3]
            R_want = Twb[:3, :3] @ T_b[:3, :3]
            T_got = poses[f"arm{aid}_pen_tip"]
            worst = max(worst, float(np.max(np.abs(T_got[:3, 3] - p_want))))
            assert np.allclose(T_got[:3, 3], p_want, atol=1e-8), (aid, q)
            assert np.allclose(T_got[:3, :3], R_want, atol=1e-8), (aid, q)
    assert worst < 1e-8, worst


def test_the_tool_chain_is_the_lateral_holder(root, links, joints):
    """bracket `PEN_LAT_HOLDER` along hand x, then `PEN_EXT_HOLDER` down to
    the tip — and the TCP frame sits where `frames.TCP_D` says it does.

    Both were 0.110 until 2026-09-03, when the photo of the real gripper put
    the tip ~5 cm below the Fat blades' plates (frames.py).  The pair is
    USER-SPECIFIED, never gate-validated; only the INLINE pen's 0.110 was."""
    for aid in FLEET_PROPOSED:
        p = f"arm{aid}_"
        assert joints[f"{p}tcp_weld"].find("parent").get("link") == \
            f"{p}panda_hand"
        assert np.allclose(_origin_of(joints[f"{p}tcp_weld"])[:3, 3],
                           [0, 0, D_HAND_TCP], atol=1e-9)
        assert np.allclose(_origin_of(joints[f"{p}pen_body_weld"])[:3, 3],
                           [PEN_LAT_HOLDER, 0, 0], atol=1e-9)
        assert np.allclose(_origin_of(joints[f"{p}pen_tip_weld"])[:3, 3],
                           [0, 0, PEN_EXT_HOLDER], atol=1e-9)
        # `pen_bracket` / `pen_body` are STATIC_CAPSULES_LAT written out — the
        # L-shaped envelope the study gated every pose against.  They are
        # COLLISION-ONLY: the real holder is not an L, and drawing one would
        # be a lie, but a checker still gets what the planner certified.
        for name, r, L in ((f"{p}pen_bracket", rig_final.BRACKET_R_LAT,
                            PEN_LAT_HOLDER),
                           (f"{p}pen_body", rig_final.PEN_R_LAT, PEN_EXT_HOLDER)):
            assert links[name].find("visual") is None, name
            cyl = links[name].find("collision/geometry/cylinder")
            assert float(cyl.get("radius")) == pytest.approx(r, abs=1e-9)
            assert float(cyl.get("length")) == pytest.approx(L, abs=1e-9)
        # the tip is a FRAME: a marker, never an obstacle
        assert links[f"{p}pen_tip"].find("collision") is None


