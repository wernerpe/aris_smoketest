def _box_of(link, kind="collision"):
    e = link.find(kind)
    xyz = np.array([float(v) for v in e.find("origin").get("xyz").split()])
    size = np.array([float(v) for v in e.find("geometry/box").get("size").split()])
    return xyz - size / 2, xyz + size / 2


