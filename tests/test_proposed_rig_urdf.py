def _rpy(r, p, y):
    return frames.rotz(y) @ frames.roty(p) @ frames.rotx(r)


def _origin_of(el):
    """(4,4) from a URDF <origin> child (missing -> identity)."""
    o = el.find("origin")
    xyz = [0.0, 0.0, 0.0]
    rpy = [0.0, 0.0, 0.0]
    if o is not None:
        if o.get("xyz"):
            xyz = [float(v) for v in o.get("xyz").split()]
        if o.get("rpy"):
            rpy = [float(v) for v in o.get("rpy").split()]
    T = np.eye(4)
    T[:3, :3] = _rpy(*rpy)
    T[:3, 3] = xyz
    return T


