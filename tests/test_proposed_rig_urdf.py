def test_own_mount_is_collision_filtered_out(root):
    """`mounts.obstacles_for` hands an arm every OTHER arm's hardware and
    never its own.  The URDF says the same — and it says it with the literal
    `drake:` prefix, because drake's parser matches the prefix as a string
    and silently ignores any other one."""
    assert b"xmlns:drake=" in INSTALLATION.read_bytes()
    groups = {g.get("name"): g for g in
              root.findall(f"{DRAKE_NS}collision_filter_group")}
    for aid in FLEET_PROPOSED:
        body = groups[f"arm{aid}_body"]
        ign = [x.get("name") for x in
               body.findall(f"{DRAKE_NS}ignored_collision_filter_group")]
        assert ign == [f"mount{aid}"]
        members = {m.get("link") for m in groups[f"mount{aid}"]
                   .findall(f"{DRAKE_NS}member")}
        assert members == {f"mount{aid}_plate", f"mount{aid}_boom"}
        # ... and only its own
        assert not any(f"mount{other}" in ign for other in FLEET_PROPOSED
                       if other != aid)
